// Writes supabase/migrations/20261023120100_cms_seed.sql from the default
// content in src/content/defaults.ts and src/lib/calculator.ts, so the
// database starts with exactly what the website shows without Supabase.
//
// Run: npm run cms:seed-sql
import { writeFileSync } from 'node:fs';
import { defaultBusiness, defaultFaqs, defaultProjects, staticPhotos } from '../src/content/defaults.ts';
import { defaultCalculatorConfig } from '../src/lib/calculator.ts';

const text = (value: string | null | undefined) => (value === null || value === undefined ? 'null' : `'${value.replace(/'/g, "''")}'`);
const textArray = (values: string[]) => (values.length ? `array[${values.map(text).join(', ')}]::text[]` : `'{}'::text[]`);

const altFor = new Map<string, { nl: string; en: string }>();
for (const project of defaultProjects) {
  for (const photo of project.photos) {
    if (altFor.has(photo.key)) continue;
    const place = project.location ? ` – ${project.location}` : '';
    altFor.set(photo.key, {
      nl: photo.captionNl ? `${project.titleNl}: ${photo.captionNl.toLowerCase()}` : `${project.titleNl}${project.titleNl.includes(project.location ?? '\u0000') ? '' : place}`,
      en: photo.captionEn ? `${project.titleEn}: ${photo.captionEn.toLowerCase()}` : `${project.titleEn}${project.titleEn.includes(project.location ?? '\u0000') ? '' : place}`,
    });
  }
}

const lines: string[] = [
  '-- Generated by scripts/generate-cms-seed.ts from src/content/defaults.ts and',
  '-- src/lib/calculator.ts. Do not edit by hand; change those files and run',
  '-- `npm run cms:seed-sql`. Existing rows are never overwritten.',
  '',
  '-- Business details',
  `insert into public.business_settings (id, company_name, legal_name, phone_display, phone_link, whatsapp_number, email, address_nl, address_en, hours_nl, hours_en, instagram_url, facebook_url, tiktok_url, service_areas) values (1, ${[
    defaultBusiness.companyName, defaultBusiness.legalName, defaultBusiness.phoneDisplay, defaultBusiness.phoneLink, defaultBusiness.whatsappNumber,
    defaultBusiness.email, defaultBusiness.addressNl, defaultBusiness.addressEn, defaultBusiness.hoursNl, defaultBusiness.hoursEn,
    defaultBusiness.instagramUrl, defaultBusiness.facebookUrl, defaultBusiness.tiktokUrl,
  ].map(text).join(', ')}, ${textArray(defaultBusiness.serviceAreas)}) on conflict (id) do nothing;`,
  '',
  '-- Photos that ship with the website',
];

for (const photo of staticPhotos) {
  const alt = altFor.get(photo.key) ?? { nl: 'Projectfoto Denra Badkamers', en: 'Denra Badkamers project photo' };
  lines.push(`insert into public.media (static_key, width, height, alt_nl, alt_en) values (${text(photo.key)}, ${photo.width}, ${photo.height}, ${text(alt.nl)}, ${text(alt.en)}) on conflict (static_key) do nothing;`);
}

lines.push('', '-- Projects');
defaultProjects.forEach((project, index) => {
  lines.push(
    `insert into public.projects (slug, category, title_nl, title_en, summary_nl, summary_en, location, review_ref, status, is_featured, sort_order, cover_media_id) values (${[
      text(project.slug), text(project.category), text(project.titleNl), text(project.titleEn), text(project.summaryNl), text(project.summaryEn),
      text(project.location), text(project.reviewRef ?? null), `'published'`, String(project.isFeatured), String((index + 1) * 10),
      `(select id from public.media where static_key = ${text(project.coverKey)})`,
    ].join(', ')}) on conflict (slug) do nothing;`,
  );
  project.photos.forEach((photo, photoIndex) => {
    lines.push(
      `insert into public.project_photos (project_id, media_id, sort_order, kind, caption_nl, caption_en) select p.id, m.id, ${photoIndex * 10}, ${text(photo.kind ?? 'result')}, ${text(photo.captionNl ?? '')}, ${text(photo.captionEn ?? '')} from public.projects p, public.media m where p.slug = ${text(project.slug)} and m.static_key = ${text(photo.key)} on conflict (project_id, media_id) do nothing;`,
    );
  });
});

lines.push('', '-- FAQs');
for (const faq of defaultFaqs) {
  lines.push(`insert into public.faqs (id, page, question_nl, answer_nl, question_en, answer_en, is_visible, sort_order) values (${[
    text(faq.id), text(faq.page), text(faq.questionNl), text(faq.answerNl), text(faq.questionEn), text(faq.answerEn), String(faq.isVisible), String(faq.sortOrder),
  ].join(', ')}) on conflict (id) do nothing;`);
}

lines.push('', '-- Calculator (prices from the original configurator)');
for (const room of defaultCalculatorConfig.rooms) {
  lines.push(`insert into public.calculator_rooms (room_type, label_nl, label_en, description_nl, description_en, base_price, included_area, is_active) values (${[
    text(room.roomType), text(room.labelNl), text(room.labelEn), text(room.descriptionNl), text(room.descriptionEn), String(room.basePrice), String(room.includedArea), String(room.isActive),
  ].join(', ')}) on conflict (room_type) do nothing;`);
  for (const tier of room.tiers) {
    lines.push(`insert into public.calculator_tiers (room_type, from_area, rate_per_m2) values (${text(room.roomType)}, ${tier.fromArea}, ${tier.ratePerM2}) on conflict (room_type, from_area) do nothing;`);
  }
}
for (const option of defaultCalculatorConfig.options) {
  lines.push(`insert into public.calculator_options (id, group_id, label_nl, label_en, price, included_nl, included_en, note_nl, note_en, rooms, conflicts_with, is_active, sort_order) values (${[
    text(option.id), text(option.group), text(option.labelNl), text(option.labelEn), String(option.price), text(option.includedNl), text(option.includedEn),
    text(option.noteNl), text(option.noteEn), textArray(option.rooms), textArray(option.conflictsWith), String(option.isActive), String(option.sortOrder),
  ].join(', ')}) on conflict (id) do nothing;`);
}

const target = new URL('../supabase/migrations/20261023120100_cms_seed.sql', import.meta.url);
writeFileSync(target, `${lines.join('\n')}\n`);
console.log(`Wrote ${lines.length} lines to ${target.pathname}`);
